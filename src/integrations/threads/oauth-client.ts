/**
 * Threads OAuth provider client interface + mock (PB-P0-003 slice B).
 *
 * Mock-first: this module defines the ports the OAuth flow will use and a
 * deterministic mock for tests. No network transport is implemented in this
 * slice; the HTTP adapter lands with the route work.
 *
 * Security notes:
 * - Requested scopes (THREADS_SCOPES) are NEVER treated as granted. Granted
 *   scopes only come from verified provider evidence; until then they stay
 *   empty and all scope-dependent actions remain disabled.
 * - Tokens returned by the client are plaintext IN MEMORY ONLY for the
 *   duration of the exchange; persistence goes through token-crypto first.
 */

import type { ThreadsOAuthConfig } from '../../config';

export const THREADS_AUTHORIZE_URL = 'https://threads.com/oauth/authorize';

export class ThreadsOAuthError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'ThreadsOAuthError';
  }
}

/** Parameters for building the Meta Authorization Window URL. */
export interface AuthorizeUrlParams {
  /**
   * Caller-supplied OAuth state. Must be a non-empty cryptographically random
   * value (>=128 bits) generated by the caller; this builder NEVER generates
   * state itself.
   */
  state: string;
}

export function buildAuthorizeUrl(config: ThreadsOAuthConfig, params: AuthorizeUrlParams): string {
  if (typeof params.state !== 'string' || params.state.length === 0) {
    throw new ThreadsOAuthError('state must be a non-empty caller-generated value');
  }
  if (!config.appId) {
    throw new ThreadsOAuthError('appId must be configured');
  }
  if (!config.redirectUri) {
    throw new ThreadsOAuthError('redirectUri must be configured');
  }
  if (config.scopes.length === 0 || !config.scopes.includes('threads_basic')) {
    throw new ThreadsOAuthError('scopes must be configured and include threads_basic');
  }

  const url = new URL(THREADS_AUTHORIZE_URL);
  url.searchParams.set('client_id', config.appId);
  url.searchParams.set('redirect_uri', config.redirectUri);
  url.searchParams.set('response_type', 'code');
  url.searchParams.set('state', params.state);
  url.searchParams.set('scope', config.scopes.join(','));
  return url.toString();
}

// --- Provider exchange types -------------------------------------------------

/** Response of the authorization-code -> short-lived-token exchange. */
export interface ShortLivedTokenResult {
  accessToken: string;
  tokenType?: string;
  /** Immutable Meta/Threads user id from the token exchange. */
  userId: string;
}

/** Response of the short-lived -> long-lived token exchange / refresh. */
export interface LongLivedTokenResult {
  accessToken: string;
  tokenType?: string;
  /** Seconds until expiry, as reported by the provider. */
  expiresInSeconds?: number;
}

/** Identity evidence from the provider (GET /me). */
export interface ThreadsIdentity {
  /** Immutable Threads user id; must match the token-exchange user_id. */
  id: string;
  username?: string;
}

/**
 * Granted-scope evidence. ONLY a positively verified provider response may
 * produce `verified: true` with a scope list. Anything else (including
 * requested scopes and scope-shaped fields in token responses, unless Meta
 * documentation confirms they enumerate actual grants) must be reported as
 * `verified: false` with an empty list.
 */
export interface GrantedScopesEvidence {
  verified: boolean;
  scopes: string[];
}

/** Provider error categories mapped by the OAuth flow. */
export type ThreadsOAuthErrorKind =
  | 'invalid_code'
  | 'provider_unavailable'
  | 'token_expired'
  | 'revoked'
  | 'permission_denied'
  | 'unknown';

export class ThreadsOAuthProviderError extends Error {
  readonly kind: ThreadsOAuthErrorKind;

  constructor(kind: ThreadsOAuthErrorKind, message: string) {
    super(message);
    this.name = 'ThreadsOAuthProviderError';
    this.kind = kind;
  }
}

/**
 * Provider client port. The mock implements this deterministically; the HTTP
 * adapter (slice C+) wires the documented endpoints.
 */
export interface ThreadsOAuthClient {
  buildAuthorizeUrl(params: AuthorizeUrlParams): string;
  exchangeCode(code: string): Promise<ShortLivedTokenResult>;
  exchangeLongLived(shortLivedToken: string): Promise<LongLivedTokenResult>;
  refreshLongLived(longLivedToken: string): Promise<LongLivedTokenResult>;
  getMe(accessToken: string): Promise<ThreadsIdentity>;
  getGrantedScopes(accessToken: string): Promise<GrantedScopesEvidence>;
}

// --- Deterministic mock ------------------------------------------------------

export interface MockThreadsOAuthClientOptions {
  config: ThreadsOAuthConfig;
  /** User id returned by exchangeCode/getMe. Default: 'mock-threads-user-1'. */
  userId?: string;
  username?: string;
  /** Granted-scope evidence; defaults to unverified/empty (fail closed). */
  grantedScopes?: GrantedScopesEvidence;
  /** When set, exchangeCode fails with this error kind. */
  failExchangeCode?: ThreadsOAuthErrorKind;
}

/**
 * Deterministic mock of ThreadsOAuthClient for tests. Performs no I/O;
 * returns fixed dummy tokens clearly marked non-real. Default granted-scope
 * evidence is UNVERIFIED with an empty list — requested scopes are never
 * echoed back as granted.
 */
export class MockThreadsOAuthClient implements ThreadsOAuthClient {
  readonly calls: { method: string }[] = [];

  private readonly config: ThreadsOAuthConfig;
  private readonly userId: string;
  private readonly username: string | undefined;
  private readonly grantedScopes: GrantedScopesEvidence;
  private readonly failExchangeCode: ThreadsOAuthErrorKind | undefined;

  constructor(options: MockThreadsOAuthClientOptions) {
    this.config = options.config;
    this.userId = options.userId ?? 'mock-threads-user-1';
    this.username = options.username;
    this.grantedScopes = options.grantedScopes ?? { verified: false, scopes: [] };
    this.failExchangeCode = options.failExchangeCode;
  }

  buildAuthorizeUrl(params: AuthorizeUrlParams): string {
    this.calls.push({ method: 'buildAuthorizeUrl' });
    return buildAuthorizeUrl(this.config, params);
  }

  exchangeCode(code: string): Promise<ShortLivedTokenResult> {
    this.calls.push({ method: 'exchangeCode' });
    if (this.failExchangeCode) {
      return Promise.reject(
        new ThreadsOAuthProviderError(this.failExchangeCode, 'mock provider exchange failure'),
      );
    }
    if (typeof code !== 'string' || code.length === 0) {
      return Promise.reject(
        new ThreadsOAuthProviderError('invalid_code', 'mock: authorization code must be non-empty'),
      );
    }
    return Promise.resolve({
      accessToken: 'mock-short-lived-token-NOT-REAL',
      tokenType: 'bearer',
      userId: this.userId,
    });
  }

  exchangeLongLived(shortLivedToken: string): Promise<LongLivedTokenResult> {
    this.calls.push({ method: 'exchangeLongLived' });
    if (shortLivedToken.length === 0) {
      return Promise.reject(
        new ThreadsOAuthProviderError('unknown', 'mock: short-lived token must be non-empty'),
      );
    }
    return Promise.resolve({
      accessToken: 'mock-long-lived-token-NOT-REAL',
      tokenType: 'bearer',
      expiresInSeconds: 60 * 24 * 60 * 60, // ~60 days per Meta docs
    });
  }

  refreshLongLived(longLivedToken: string): Promise<LongLivedTokenResult> {
    this.calls.push({ method: 'refreshLongLived' });
    if (longLivedToken.length === 0) {
      return Promise.reject(
        new ThreadsOAuthProviderError('token_expired', 'mock: token must be non-empty'),
      );
    }
    return Promise.resolve({
      accessToken: 'mock-refreshed-long-lived-token-NOT-REAL',
      tokenType: 'bearer',
      expiresInSeconds: 60 * 24 * 60 * 60,
    });
  }

  getMe(accessToken: string): Promise<ThreadsIdentity> {
    this.calls.push({ method: 'getMe' });
    if (accessToken.length === 0) {
      return Promise.reject(
        new ThreadsOAuthProviderError('revoked', 'mock: access token must be non-empty'),
      );
    }
    return Promise.resolve({
      id: this.userId,
      ...(this.username ? { username: this.username } : {}),
    });
  }

  getGrantedScopes(accessToken: string): Promise<GrantedScopesEvidence> {
    this.calls.push({ method: 'getGrantedScopes' });
    if (accessToken.length === 0) {
      return Promise.reject(
        new ThreadsOAuthProviderError('revoked', 'mock: access token must be non-empty'),
      );
    }
    return Promise.resolve(this.grantedScopes);
  }
}
